let language = 'en';
try { if(localStorage.getItem('blackburn-language') === 'ru') language = 'ru'; } catch {}
export const lang = () => language;
export const t = english => language === 'ru' ? russian[english] ?? english : english;
const staticText = [];
const staticAttributes = [];
export function prepareLanguage(){
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for(let n=walker.nextNode(); n; n=walker.nextNode()){
    if(n.parentElement.closest('script,style,[lang="ru"]')) continue;
    const source=n.textContent.trim();
    if(Object.hasOwn(russian,source)) staticText.push([n,n.textContent,source]);
  }
  for(const el of document.querySelectorAll('[aria-label],[title]')){
    for(const attr of ['aria-label','title']){
      const source=el.getAttribute(attr);
      if(source && Object.hasOwn(russian,source)) staticAttributes.push([el,attr,source]);
    }
  }
}
export function setLanguage(value){
  language=value==='ru'?'ru':'en';
  try{localStorage.setItem('blackburn-language',language);}catch{}
  document.documentElement.lang=language;
  document.title='Blackburn Type D • '+t('Flight archive');
  for(const [node,raw,source] of staticText)node.textContent=raw.replace(source,t(source));
  for(const [el,attr,source] of staticAttributes)el.setAttribute(attr,t(source));
  for(const [id,code] of [['langEn','en'],['langRu','ru']])document.getElementById(id).setAttribute('aria-pressed',String(code===language));
}
